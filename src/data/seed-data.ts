import { ColoringPack, ColoringSheet } from '../types';

function makeSheet(
  id: string,
  packSlug: string,
  titleEn: string,
  extra: Partial<Omit<ColoringSheet, 'title'>> & {
    category: ColoringSheet['category'];
    title?: Partial<ColoringSheet['title']>;
    descriptionEn: string;
    tags: string[];
    views: number;
    upvotes: number;
    downvotes: number;
    weeklyGrowthPct: number;
    difficulty: ColoringSheet['difficulty'];
    ageRange: string;
    rank?: number;
    isNew?: boolean;
  }
): ColoringSheet {
  return {
    id,
    packSlug,
    title: {
      en: titleEn,
      ...extra.title,
    },
    description: {
      en: extra.descriptionEn,
    },
    category: extra.category,
    difficulty: extra.difficulty,
    ageRange: extra.ageRange,
    tags: extra.tags,
    views: extra.views,
    upvotes: extra.upvotes,
    downvotes: extra.downvotes,
    weeklyGrowthPct: extra.weeklyGrowthPct,
    rank: extra.rank,
    isNew: extra.isNew,
    createdAt: extra.createdAt || '2026-11-18',
    thumbnailUrl: extra.thumbnailUrl || `/cdn/thumbs/${id}.svg`,
    lineArtUrl: extra.lineArtUrl || `/cdn/lineart/${id}.svg`,
    sourcePdfUrl: extra.sourcePdfUrl,
    pdfUrls: extra.pdfUrls || {
      a4: `/cdn/pdfs/a4/${id}.pdf`,
      letter: `/cdn/pdfs/letter/${id}.pdf`,
    },
  };
}

